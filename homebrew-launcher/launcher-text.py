
"""Build OZLauncher's antialiased type atlas (no runtime font dependency)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent / "shaders"
root.mkdir(parents=True, exist_ok=True)

ATLAS_WIDTH = 1024
ATLAS_HEIGHT = 2048
FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

atlas = Image.new("L", (ATLAS_WIDTH, ATLAS_HEIGHT), 0)
draw = ImageDraw.Draw(atlas)

labels = [
    ("TITLE", "OZLauncher", 88),
    ("SUBTITLE", "V 1.0", 24),
    ("PLATFORM", "N I N T E N D O   S W I T C H   2", 16),

    ("LIBRARY", "Game Library", 26),
    ("COUNT1", "1 game", 18),
    ("COUNT2", "2 games", 18),
    ("COUNT3", "3 games", 18),
    ("APPS", "Games & Apps", 18),

    ("NOTITLES", "Your library is empty", 34),
    ("EMPTYHINT", "Add a title to get started.", 20),

    ("SELECT", "Open", 19),
    ("BACK", "Back", 19),

    ("EMPTY", "Unable to launch", 34),
    ("DETAIL", "Check the app and try again.", 19),
    ("CLOSE", "Press B to return", 18),

    ("BUTTON_A", "A", 16),
    ("BUTTON_B", "B", 16),

    ("CREDIT", "Developed by OZLabs", 18),
]

labels += [(f"DIGIT{i}", str(i), 34) for i in range(10)]

header = [
    "// Generated by homebrew-launcher/launcher-text.py.",
    "// OZLauncher V 1.0 — text-atlas coordinates.",
    "// Atlas pixels follow the 1024-byte state buffer.",
]

y = 2

for name, text, size in labels:
    face = ImageFont.truetype(FONT_PATH, size)

    bounds = draw.textbbox((0, 0), text, font=face)
    width = bounds[2] - bounds[0]
    height = bounds[3] - bounds[1]

    if width + 4 > ATLAS_WIDTH:
        raise ValueError(
            f"{name} is too wide for the {ATLAS_WIDTH}-pixel atlas"
        )

    if y + height + 2 > ATLAS_HEIGHT:
        raise ValueError(
            f"{name} exceeds the {ATLAS_HEIGHT}-pixel atlas height"
        )

    draw.text(
        (2 - bounds[0], y - bounds[1]),
        text,
        fill=255,
        font=face,
    )

    header.append(
        f"const ivec4 TEXT_{name} = ivec4(2, {y}, {width}, {height});"
    )

    y += height + 8

header.append(
    "const ivec4 DIGITS[10] = ivec4[10]("
    + ",".join(f"TEXT_DIGIT{i}" for i in range(10))
    + ");"
)

(root / "launcher-text.bin").write_bytes(atlas.tobytes())
(root / "launcher-text.glsl").write_text(
    "\n".join(header) + "\n",
    encoding="utf-8",
)
atlas.save(root / "launcher-text.png")

print(f"OZLauncher text atlas: {ATLAS_WIDTH} x {ATLAS_HEIGHT}")
print(f"Labels generated: {len(labels)}")
print(f"Atlas rows used: {y}")
